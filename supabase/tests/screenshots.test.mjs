import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { test } from 'node:test';

test('multiple screenshots preserve legacy data, enforce ownership and limits, and return all cleanup paths', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,is_anonymous boolean default false);
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      grant usage on schema auth,public to anon,authenticated;
      grant execute on function auth.uid(),auth.jwt() to anon,authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb);`);
    await db.exec(await readFile(new URL('../initialize.sql', import.meta.url), 'utf8'));
    const developer = randomUUID(), anonymous = randomUUID(), project = randomUUID(), env = randomUUID(), foreignEnv = randomUUID();
    await db.query('insert into auth.users(id,email,is_anonymous) values($1,$2,false),($3,$4,true)', [developer,'dev@example.com',anonymous,'anonymous@example.com']);
    const as = async (id, role = 'authenticated') => {
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claims',$1,false)", [JSON.stringify(id ? { sub:id, is_anonymous:id === anonymous } : {})]);
      await db.exec(`set role ${role}`);
    };
    const report = async (secret, target, operation, payload) => (await db.query('select public.report_operation($1,$2,$3,$4) as data', [secret,target,operation,payload])).rows[0].data;
    const context = { url:'https://one.example/',origin:'https://one.example',pagePath:'/',anchor:{kind:'pin',documentX:10,documentY:20},viewport:{width:1200,height:800,devicePixelRatio:1},scroll:{x:0,y:0} };
    await as(developer);
    await db.query('insert into public.projects(id,name,created_by) values($1,$2,$3)', [project,'Project',developer]);
    await db.query('insert into public.environments(id,project_id,name,origin) values($1,$2,$3,$4),($5,$2,$6,$7)', [env,project,'Production','https://one.example',foreignEnv,'Other','https://other.example']);
    const legacy = randomUUID(), legacyPath = `${project}/${legacy}.jpg`;
    await report(null,env,'create',{id:legacy,body:'Historical report',context});
    await report(null,env,'reply',{id:legacy,body:'Historical reply'});
    await db.exec('reset role');
    await db.query('update public.issues set screenshot_path=$1 where id=$2', [legacyPath,legacy]);
    await db.exec('reset role; alter table public.issues drop column screenshot_paths');
    const migration = await readFile(new URL('../report_screenshots.sql', import.meta.url),'utf8');
    await db.exec(migration);
    await db.exec(migration);
    assert.equal((await db.query('select count(*) as n from auth.users')).rows[0].n,2);
    await as(developer);
    const thread = await report(null,env,'thread',{id:legacy});
    assert.equal(thread.comments[0].body,'Historical reply');
    assert.deepEqual(thread.issue.screenshot_paths,[legacyPath]);
    const link = (await db.query('select token from public.environment_review_links where environment_id=$1',[env])).rows[0].token;
    const guest = 'a'.repeat(64), code = 'b'.repeat(64), secret = 'c'.repeat(64);
    await as(null,'anon');
    await db.query('select public.start_guest_session($1,$2,$3)',[link,'Reviewer',guest]);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[guest,code]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[code,secret]);
    const issue = randomUUID();
    await report(secret,env,'create',{id:issue,body:'New screenshots',context});
    await assert.rejects(report(secret,env,'screenshot_prepare',{id:legacy,screenshotId:randomUUID()}),/Not authorized/);
    await assert.rejects(report(secret,foreignEnv,'screenshot_prepare',{id:issue,screenshotId:randomUUID()}),/unavailable/);
    await assert.rejects(report(secret,env,'screenshot',{id:issue,screenshotId:randomUUID()}),/unavailable/);
    const screenshotIds = Array.from({length:5},()=>randomUUID());
    const paths = screenshotIds.map(id=>`${project}/${issue}/${id}.jpg`);
    for (let i=0;i<5;i++) {
      await report(secret,env,'screenshot_prepare',{id:issue,screenshotId:screenshotIds[i]});
      await db.exec('reset role');
      await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['screenshots',paths[i],{size:2500000,mimetype:'image/jpeg'}]);
      await as(null,'anon');
      await report(secret,env,'screenshot',{id:issue,screenshotId:screenshotIds[i]});
    }
    await report(secret,env,'screenshot',{id:issue,screenshotId:screenshotIds[0]});
    const saved = (await report(secret,env,'thread',{id:issue})).issue;
    assert.deepEqual(saved.screenshot_paths,paths);
    assert.equal(saved.screenshot_path,paths[0]);
    await assert.rejects(report(secret,env,'screenshot_prepare',{id:issue,screenshotId:randomUUID()}),/Maximum 5/);
    await assert.rejects(report(secret,env,'screenshot',{id:issue,screenshotId:randomUUID()}),/Maximum 5/);
    await assert.rejects(report(secret,env,'delete',{id:issue}),/Not authorized/);
    const readToken='d'.repeat(64),readCode='e'.repeat(64),readSecret='f'.repeat(64);
    await db.query('select public.start_guest_session($1,$2,$3)',[link,null,readToken]);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[readToken,readCode]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[readCode,readSecret]);
    assert.deepEqual((await report(readSecret,env,'thread',{id:issue})).issue.screenshot_paths,paths);
    await assert.rejects(report(readSecret,env,'screenshot_prepare',{id:issue,screenshotId:randomUUID()}),/REVIEWER_NAME_REQUIRED/);
    await assert.rejects(report(readSecret,env,'screenshot',{id:issue,screenshotId:screenshotIds[0]}),/REVIEWER_NAME_REQUIRED/);
    await as(anonymous);
    await assert.rejects(report(null,env,'thread',{id:issue}),/Not authorized/);
    await as(developer);
    await db.query('select public.regenerate_environment_review_link($1)',[env]);
    await as(null,'anon');
    await assert.rejects(report(secret,env,'screenshot_prepare',{id:issue,screenshotId:screenshotIds[0]}),/revoked/);
    await as(developer);
    const deleted = await report(null,env,'delete',{id:issue});
    assert.deepEqual(deleted.screenshot_paths,paths);
    await db.exec('reset role');
    assert.equal((await db.query('select count(*) as n from storage.objects')).rows[0].n,5);
    await db.exec(migration);
    await as(developer);
    assert.deepEqual((await report(null,env,'thread',{id:legacy})).issue.screenshot_paths,[legacyPath]);
    const widget=(await db.query('select * from public.environment_widgets where environment_id=$1',[env])).rows[0];
    await db.query('update public.environment_widgets set enabled=true where environment_id=$1',[env]);
    const widgetSecret='1'.repeat(64),widgetIssue=randomUUID(),widgetScreenshot=randomUUID();
    const widgetPath=`${project}/${widgetIssue}/${widgetScreenshot}.jpg`;
    await as(null,'anon');
    await db.query('select public.start_widget_session($1,$2,$3,$4)',[widget.public_key,'https://one.example','Widget reviewer',widgetSecret]);
    await report(widgetSecret,env,'create',{id:widgetIssue,body:'Widget screenshot',context});
    await report(widgetSecret,env,'screenshot_prepare',{id:widgetIssue,screenshotId:widgetScreenshot});
    await assert.rejects(report(widgetSecret,foreignEnv,'screenshot_prepare',{id:widgetIssue,screenshotId:widgetScreenshot}),/unavailable/);
    await db.exec('reset role');
    await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['screenshots',widgetPath,{size:10,mimetype:'image/png'}]);
    await as(null,'anon');
    await assert.rejects(report(widgetSecret,env,'screenshot',{id:widgetIssue,screenshotId:widgetScreenshot}),/unavailable/);
    await db.exec('reset role');
    await db.query('update storage.objects set metadata=$1 where name=$2',[{size:2500001,mimetype:'image/jpeg'},widgetPath]);
    await as(null,'anon');
    await assert.rejects(report(widgetSecret,env,'screenshot',{id:widgetIssue,screenshotId:widgetScreenshot}),/unavailable/);
    await db.exec('reset role');
    await db.query('update storage.objects set metadata=$1 where name=$2',[{size:10,mimetype:'image/jpeg'},widgetPath]);
    await as(developer);
    await db.query('update public.environment_widgets set enabled=false where environment_id=$1',[env]);
    await as(null,'anon');
    await assert.rejects(report(widgetSecret,env,'screenshot',{id:widgetIssue,screenshotId:widgetScreenshot}),/disabled/);
    await as(developer);
    await db.query('update public.environment_widgets set enabled=true where environment_id=$1',[env]);
    await as(null,'anon');
    await report(widgetSecret,env,'screenshot',{id:widgetIssue,screenshotId:widgetScreenshot});
    await as(developer);
    const cleanup = (await db.query('select public.platform_delete_resource($1,$2) as data',[project,'project'])).rows[0].data;
    assert.ok(cleanup.includes(legacyPath));
    assert.ok(cleanup.includes(widgetPath));
  } finally { await db.close(); }
});
