import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { test } from 'node:test';

for (const migrate of [false,true]) test(`notification paging: ${migrate?'incremental':'fresh'}, filtered pages, polling summaries, reading and recipient isolation`, async () => {
  const db=new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,is_anonymous boolean default false);
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      grant usage on schema auth,public to anon,authenticated; grant execute on function auth.uid(),auth.jwt() to anon,authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb);`);
    const initialize=await readFile(new URL('../initialize.sql',import.meta.url),'utf8');
    await db.exec(migrate?initialize.split('-- Incremental notification pagination;')[0]:initialize);
    const dev=randomUUID(),other=randomUUID(),anonymous=randomUUID();
    await db.query('insert into auth.users(id,email,is_anonymous) values($1,$2,false),($3,$4,false),($5,$6,true)',[dev,'dev@example.com',other,'other@example.com',anonymous,'anon@example.com']);
    const as=async(id,role=id?'authenticated':'anon')=>{
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify(id?{sub:id,is_anonymous:id===anonymous}:{})]);
      await db.exec(`set role ${role}`);
    };
    await as(dev);
    const project=(await db.query("select public.create_project_with_production('First','https://first.example') id")).rows[0].id;
    const env=(await db.query('select id from public.environments where project_id=$1',[project])).rows[0].id;
    const env2=randomUUID();
    await db.query("insert into public.environments(id,project_id,name,origin) values($1,$2,'Staging','https://stage.example')",[env2,project]);
    const otherProject=(await db.query("select public.create_project_with_production('Second','https://second.example') id")).rows[0].id;
    const otherEnv=(await db.query('select id from public.environments where project_id=$1',[otherProject])).rows[0].id;
    await db.exec('reset role');
    const issues=[randomUUID(),randomUUID(),randomUUID(),randomUUID()];
    const context={url:'https://first.example/',origin:'https://first.example',pagePath:'/',anchor:{kind:'pin',documentX:1,documentY:2},viewport:{width:1280,height:800,devicePixelRatio:1},scroll:{x:0,y:0}};
    for(let i=0;i<4;i++) await db.query('insert into public.issues(id,project_id,environment_id,page_path,body,author_id,context) values($1,$2,$3,$4,$5,$6,$7)',[issues[i],i===2?otherProject:project,i===2?otherEnv:i===1?env2:env,i===3?'/other':'/', 'x'.repeat(1000),dev,context]);
    await db.exec('delete from public.notifications');
    const ids=Array.from({length:65},()=>randomUUID());
    for(let i=0;i<65;i++) await db.query(`insert into public.notifications(id,issue_id,user_id,status,actor_name,kind,created_at,read_at)
      values($1,$2,$3,$4,'Actor','created','2026-01-01'::timestamptz + $5 * interval '1 second',case when $5<10 then now() else null end)`,[ids[i],issues[i<50?0:i<60?1:2],dev,i%2?'open':'resolved',i]);
    const foreignId=randomUUID();
    await db.query("insert into public.notifications(id,issue_id,user_id,status,actor_name,kind) values($1,$2,$3,'open','Other','created')",[foreignId,issues[0],other]);
    if(migrate){
      const sql=await readFile(new URL('../notification_pagination.sql',import.meta.url),'utf8');
      await db.exec(sql);await db.exec(sql);
      assert.equal((await db.query('select count(*)::int n from public.notifications')).rows[0].n,66);
      assert.equal((await db.query('select count(*)::int n from public.notifications where read_at is not null')).rows[0].n,10);
    }
    const page=async(payload={},secret=null,target=null)=>(await db.query('select public.notification_page($1,$2,$3) result',[secret,target,payload])).rows[0].result;
    const op=async(operation,payload={},secret=null,target=null)=>(await db.query('select public.notification_operation($1,$2,$3,$4) result',[secret,target,operation,{...payload,paginated:true}])).rows[0].result;
    await as(dev);
    const first=await page(),second=await page({offset:20}),third=await page({offset:40}),fourth=await page({offset:60});
    assert.equal(first.items.length,20);assert.equal(fourth.items.length,5);assert.equal(first.total,65);assert.equal(first.unread,55);
    assert.deepEqual([...first.items,...second.items,...third.items,...fourth.items].map(row=>row.id),[...ids].reverse());
    assert.equal((await page({reads:['unread']})).total,55);assert.equal((await page({reads:['read']})).total,10);
    assert.equal((await page({projects:[otherProject]})).total,5);assert.equal((await page({environments:[env2]})).total,10);
    assert.equal((await page({statuses:['open']})).total,32);
    assert.equal(first.projects.length,2);assert.equal(first.environments.length,3);
    const summary=await page({mode:'summary'});
    assert.deepEqual(summary.items,[]);assert.equal(summary.arrivalCount,0);assert.equal(summary.latest,null);assert.equal(summary.unread,55);
    assert.deepEqual((await op('notifications',{mode:'summary'})).items,[]);
    await db.exec('reset role');
    for(let i=0;i<35;i++) await db.query("insert into public.notifications(issue_id,user_id,status,actor_name,kind,created_at) values($1,$2,'open','New','created','2026-02-01'::timestamptz + $3 * interval '1 second')",[issues[0],dev,i]);
    await as(dev);
    const arrivals=await page({mode:'summary',after:summary.cursor});
    assert.equal(arrivals.arrivalCount,35);assert.equal(arrivals.latest.body.length,120);assert.equal(arrivals.unread,90);assert.deepEqual(arrivals.items,[]);
    assert.equal((await page({mode:'summary',after:arrivals.cursor})).arrivalCount,0);
    const read=await op('notification_read',{id:ids[64],mode:'summary'});
    assert.equal(read.unread,89);assert.deepEqual(read.items,[]);
    await op('notification_read',{id:ids[64],mode:'summary'});
    assert.equal((await page({mode:'summary'})).unread,89);
    await assert.rejects(op('notification_read',{id:foreignId,mode:'summary'}),/unavailable/);
    const allRead=await op('notifications_read',{mode:'summary'});
    assert.equal(allRead.unread,0);assert.deepEqual(allRead.items,[]);
    assert.equal((await page({reads:['unread']})).total,0);
    await as(other);
    assert.equal((await page()).unread,1);assert.equal((await page()).items[0].id,foreignId);
    await as(anonymous);await assert.rejects(page(),/Not authorized/);
    await as(null);await assert.rejects(page(),/Not authorized/);
    await as(dev);
    const link=(await db.query('select token from public.environment_review_links where environment_id=$1',[env])).rows[0].token;
    const widget=(await db.query('select public_key from public.environment_widgets where environment_id=$1',[env])).rows[0].public_key;
    await db.query('update public.environment_widgets set enabled=true where environment_id=$1',[env]);
    await as(null);
    const guest='1'.repeat(64),code='2'.repeat(64),extension='3'.repeat(64),widgetToken='4'.repeat(64);
    await db.query('select public.start_guest_session($1,null,$2)',[link,guest]);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[guest,code]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[code,extension]);
    await db.query('select public.start_widget_session($1,$2,null,$3)',[widget,'https://first.example',widgetToken]);
    await db.exec('reset role');
    const guestId=(await db.query('select guest_session_id from public.extension_sessions where token_hash=encode(sha256(convert_to($1,\'UTF8\')),\'hex\')',[extension])).rows[0].guest_session_id;
    for(const issue of [issues[0],issues[3],issues[1]]) await db.query("insert into public.notifications(issue_id,guest_session_id,status,actor_name,kind) values($1,$2,'open','Guest','created')",[issue,guestId]);
    await as(null);
    assert.equal((await page({pagePath:'/'},extension,env)).unread,1);
    await op('notifications_read',{pagePath:'/',mode:'summary'},extension,env);
    assert.equal((await page({pagePath:'/'},extension,env)).unread,0);
    assert.equal((await page({pagePath:'/other'},extension,env)).unread,1);
    assert.equal((await page({},extension,env2)).unread,1);
    assert.deepEqual((await page({},widgetToken,env)).items,[]);
    await assert.rejects(page({},extension,otherEnv),/Not authorized|unavailable/);
    await assert.rejects(page({},widgetToken,env2),/Not authorized|unavailable/);
    await as(dev);await db.query('update public.environment_widgets set enabled=false where environment_id=$1',[env]);
    await db.query('select public.regenerate_environment_review_link($1)',[env]);
    await as(null);
    await assert.rejects(page({},widgetToken,env),/unavailable/);await assert.rejects(page({},extension,env),/revoked|unavailable/);
  }finally{await db.close();}
});
