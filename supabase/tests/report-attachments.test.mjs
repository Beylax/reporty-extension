import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import test from 'node:test';

test('report files: migration preserves data, enforces 5 MB and five files, private access, ownership, revocation and cleanup', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,is_anonymous boolean default false);
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      grant usage on schema auth,public to anon,authenticated;
      grant execute on function auth.uid(),auth.jwt() to anon,authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb);`);
    await db.exec(await readFile(new URL('../initialize.sql',import.meta.url),'utf8'));
    const developer=randomUUID(),second=randomUUID(),anonymous=randomUUID(),project=randomUUID(),env=randomUUID(),foreignEnv=randomUUID();
    await db.query('insert into auth.users(id,email,is_anonymous) values($1,$2,false),($3,$4,false),($5,$6,true)',[developer,'dev@example.com',second,'other@example.com',anonymous,'anonymous@example.com']);
    const as=async(id,role='authenticated')=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify(id?{sub:id,is_anonymous:id===anonymous}:{})]);await db.exec(`set role ${role}`);};
    const report=async(secret,target,operation,payload)=>(await db.query('select public.report_operation($1,$2,$3,$4) as data',[secret,target,operation,payload])).rows[0].data;
    const attachment=async(secret,target,operation,payload)=>(await db.query('select public.report_attachment_operation($1,$2,$3,$4) as data',[secret,target,operation,payload])).rows[0].data;
    const context={url:'https://one.example/',origin:'https://one.example',pagePath:'/',anchor:{kind:'pin',documentX:10,documentY:20},viewport:{width:1200,height:800,devicePixelRatio:1},scroll:{x:0,y:0}};
    await as(developer);
    await db.query('insert into public.projects(id,name,created_by) values($1,$2,$3)',[project,'Project',developer]);
    await db.query('insert into public.environments(id,project_id,name,origin) values($1,$2,$3,$4),($5,$2,$6,$7)',[env,project,'Production','https://one.example',foreignEnv,'Other','https://other.example']);
    const historical=randomUUID(),replyId=randomUUID(),replyFile=randomUUID();
    await report(null,env,'create',{id:historical,body:'Historical report',context});
    await report(null,env,'screenshot',{id:historical});
    const reply=(await db.query('select public.attachment_operation(null,$1,$2,$3) as data',[env,'reserve',{id:replyFile,issueId:historical,name:'old.txt',mime:'application/octet-stream',size:3}])).rows[0].data;
    await db.exec('reset role');
    await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['attachments',reply.path,{size:3}]);
    await as(developer);
    await report(null,env,'reply',{id:historical,body:'Historical reply',replyId,attachments:[replyFile]});
    await db.exec('reset role; drop function public.report_attachment_operation(text,uuid,text,jsonb); drop table public.issue_attachments;');
    const migration=await readFile(new URL('../report_attachments.sql',import.meta.url),'utf8');
    await db.exec(migration); await db.exec(migration);
    assert.equal((await db.query('select count(*) as n from auth.users')).rows[0].n,3);
    const bucket=(await db.query("select * from storage.buckets where id='report-attachments'")).rows[0];
    assert.equal(bucket.public,false);assert.equal(bucket.file_size_limit,5000000);assert.deepEqual(bucket.allowed_mime_types,['application/octet-stream']);
    assert.equal((await db.query("select file_size_limit from storage.buckets where id='attachments'")).rows[0].file_size_limit,2500000);
    await as(developer);
    const old=await report(null,env,'thread',{id:historical});
    assert.equal(old.issue.body,'Historical report');assert.ok(old.issue.screenshot_path);assert.deepEqual(old.issue.attachments,[]);
    assert.equal(old.comments[0].body,'Historical reply');assert.equal(old.comments[0].attachments[0].id,replyFile);
    const link=(await db.query('select token from public.environment_review_links where environment_id=$1',[env])).rows[0].token;
    const token='a'.repeat(64),code='b'.repeat(64),secret='c'.repeat(64);
    await as(null,'anon');
    await db.query('select public.start_guest_session($1,$2,$3)',[link,'Reviewer',token]);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[token,code]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[code,secret]);
    const issue=randomUUID();await report(secret,env,'create',{id:issue,body:'New report with files',context});
    const id=randomUUID(),payload={id,issueId:issue,name:'specification.pdf',size:5000000};
    await assert.rejects(attachment(secret,env,'reserve',{...payload,id:randomUUID(),size:5000001}),/Invalid attachment/);
    await assert.rejects(attachment(secret,env,'reserve',{...payload,id:randomUUID(),size:0}),/Invalid attachment/);
    await assert.rejects(attachment(secret,env,'reserve',{...payload,issueId:historical}),/Not authorized/);
    await assert.rejects(attachment(secret,foreignEnv,'reserve',payload),/unavailable/);
    const reserved=await attachment(secret,env,'reserve',payload);
    assert.equal(reserved.mime,'application/octet-stream');assert.equal(reserved.committed,false);
    assert.deepEqual((await report(secret,env,'thread',{id:issue})).issue.attachments,[]);
    await assert.rejects(attachment(secret,env,'read',{id,issueId:issue}),/unavailable/);
    await assert.rejects(attachment(secret,env,'commit',{id,issueId:issue}),/unavailable/);
    await assert.rejects(db.query('select * from public.issue_attachments'),/permission denied/);
    await as(second);
    await assert.rejects(attachment(null,env,'reserve',payload),/unavailable/);
    await assert.rejects(attachment(null,env,'commit',{id,issueId:issue}),/Not authorized/);
    await db.exec('reset role');
    await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['report-attachments',reserved.path,{size:5000000,mimetype:'text/html'}]);
    await as(null,'anon');await assert.rejects(attachment(secret,env,'commit',{id,issueId:issue}),/unavailable/);
    await db.exec('reset role');await db.query('update storage.objects set metadata=$1 where name=$2',[{size:4999999,mimetype:'application/octet-stream'},reserved.path]);
    await as(null,'anon');await assert.rejects(attachment(secret,env,'commit',{id,issueId:issue}),/unavailable/);
    await db.exec('reset role');await db.query('update storage.objects set metadata=$1 where name=$2',[{size:5000000,mimetype:'application/octet-stream'},reserved.path]);
    await as(null,'anon');await attachment(secret,env,'commit',{id,issueId:issue});await attachment(secret,env,'commit',{id,issueId:issue});
    assert.equal((await attachment(secret,env,'reserve',payload)).committed,true);
    assert.equal((await report(secret,env,'thread',{id:issue})).issue.attachments.length,1);
    await assert.rejects(attachment(secret,env,'remove',{id,issueId:issue}),/Not authorized/);
    const pending=[];for(let i=0;i<4;i++)pending.push(await attachment(secret,env,'reserve',{id:randomUUID(),issueId:issue,name:`file-${i}.zip`,size:1}));
    await assert.rejects(attachment(secret,env,'reserve',{id:randomUUID(),issueId:issue,name:'sixth.zip',size:1}),/Maximum 5/);
    await attachment(secret,env,'remove',{id:pending[0].id,issueId:issue});
    await assert.rejects(attachment(secret,env,'commit',{id:pending[0].id,issueId:issue}),/unavailable/);
    await attachment(secret,env,'discard',{id:pending[0].id,issueId:issue});
    await assert.rejects(attachment(secret,env,'read',{id:pending[0].id,issueId:issue}),/unavailable/);
    const readToken='d'.repeat(64),readCode='e'.repeat(64),readSecret='f'.repeat(64);
    await db.query('select public.start_guest_session($1,$2,$3)',[link,null,readToken]);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[readToken,readCode]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[readCode,readSecret]);
    assert.equal((await attachment(readSecret,env,'read',{id,issueId:issue})).path,reserved.path);
    await assert.rejects(attachment(readSecret,env,'reserve',{id:randomUUID(),issueId:issue,name:'unauthorized',size:1}),/REVIEWER_NAME_REQUIRED/);
    await as(anonymous);await assert.rejects(attachment(null,env,'read',{id,issueId:issue}),/Not authorized/);
    await as(developer);await db.query('select public.regenerate_environment_review_link($1)',[env]);
    await as(null,'anon');await assert.rejects(attachment(secret,env,'read',{id,issueId:issue}),/revoked/);
    await as(developer);
    const widget=(await db.query('select * from public.environment_widgets where environment_id=$1',[env])).rows[0];
    await db.query('update public.environment_widgets set enabled=true where environment_id=$1',[env]);
    const widgetSecret='1'.repeat(64),widgetIssue=randomUUID();await as(null,'anon');
    await db.query('select public.start_widget_session($1,$2,$3,$4)',[widget.public_key,'https://one.example','Widget reviewer',widgetSecret]);
    await report(widgetSecret,env,'create',{id:widgetIssue,body:'Widget report',context});
    const widgetFile=await attachment(widgetSecret,env,'reserve',{id:randomUUID(),issueId:widgetIssue,name:'widget.zip',size:5000000});
    await assert.rejects(attachment(widgetSecret,foreignEnv,'reserve',{id:randomUUID(),issueId:widgetIssue,name:'cross-origin.zip',size:1}),/unavailable/);
    await as(developer);await db.query('update public.environment_widgets set enabled=false where environment_id=$1',[env]);
    await as(null,'anon');await assert.rejects(attachment(widgetSecret,env,'commit',{id:widgetFile.id,issueId:widgetIssue}),/disabled/);
    await as(developer);
    const deleted=await report(null,env,'delete',{id:issue});
    assert.ok(deleted.attachment_paths.includes(reserved.path));assert.ok(deleted.attachment_paths.includes(pending[1].path));
    await db.exec('reset role');assert.equal((await db.query('select count(*) as n from storage.objects')).rows[0].n,2);
    await db.exec(migration);await as(developer);
    assert.equal((await report(null,env,'thread',{id:historical})).comments[0].attachments[0].id,replyFile);
    const cleanup=(await db.query('select public.platform_delete_resource($1,$2) as data',[project,'project'])).rows[0].data;
    assert.ok(cleanup.includes(widgetFile.path));assert.ok(cleanup.includes(reply.path));
  } finally {await db.close();}
});
