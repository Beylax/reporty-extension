import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { test } from 'node:test';

const owner = '11111111-1111-4111-8111-111111111111';
const member = '22222222-2222-4222-8222-222222222222';
const outsider = '33333333-3333-4333-8333-333333333333';
const platform = '99999999-9999-4999-8999-999999999999';
const project = '44444444-4444-4444-8444-444444444444';
const other = '55555555-5555-4555-8555-555555555555';

test('shared dashboard permissions and a single regenerable guest link', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated;
      create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, email_confirmed_at timestamptz);
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      grant usage on schema auth, public to anon, authenticated;
      grant execute on function auth.uid(), auth.jwt() to anon, authenticated;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
      insert into auth.users values ('${owner}','owner@example.com',now()), ('${member}','member@example.com',now()), ('${outsider}','outsider@example.com',now()), ('${platform}','platform@example.com',now());`);
    for (const file of ['202610050001_initial.sql', '202610050002_project_management.sql', '202610050003_invitations.sql', '202610050004_extension_sessions.sql', '202610050005_reports.sql', '202610050006_report_priorities.sql', '202610050007_user_management.sql', '202610050008_platform_management.sql', '202610050009_project_admin_permissions.sql', '202610050010_guest_review_start.sql']) await db.exec(await readFile(new URL(`../migrations/${file}`, import.meta.url), 'utf8'));
    const as = async (id, role = 'authenticated') => {
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claims', $1, false)", [JSON.stringify(id ? { sub: id, is_anonymous: false } : {})]);
      await db.exec(`set role ${role}`);
    };
    await db.query('insert into public.projects(id,name,created_by) values($1,$2,$3),($4,$5,$6)', [project,'Project',owner,other,'Other',outsider]);
    await db.query('insert into public.project_members(project_id,user_id,role) values($1,$2,$3)', [project,member,'member']);
    await db.query('insert into public.platform_admins(user_id) values($1)', [platform]);
    await db.exec(await readFile(new URL('../migrations/202610050011_shared_dashboard.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../migrations/202610050012_guest_report_updates.sql', import.meta.url), 'utf8'));
    const env = '66666666-6666-4666-8666-666666666666';
    const env2 = '77777777-7777-4777-8777-777777777777';
    await db.query('insert into public.environments(id,project_id,name,origin) values($1,$2,$3,$4),($5,$2,$6,$7)',[env,project,'Production','https://one.example',env2,'Staging','https://stage.example']);
    await as(outsider);
    assert.equal((await db.query('select * from public.projects')).rows.length,2);
    await db.query('update public.projects set name=$1 where id=$2',['Renamed by another developer',project]);
    await db.exec('reset role');
    const issue = '88888888-8888-4888-8888-888888888888';
    await db.query('insert into public.issues(id,project_id,environment_id,page_path,body,author_id,context) values($1,$2,$3,$4,$5,$6,$7)',[issue,project,env,'/','Original',owner,{}]);
    const extensionSecret='d'.repeat(64);
    await db.query("insert into public.extension_sessions(user_id,token_hash) values($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[outsider,extensionSecret]);
    await as(outsider);
    const context=(await db.query('select public.extension_context($1) as context',[extensionSecret])).rows[0].context;
    assert.equal(context.environments.length,2);
    await db.query('select public.report_operation(null,$1,$2,$3)',[env,'edit',{id:issue,body:'Edited by another developer'}]);
    await db.query('select public.report_operation($1,$2,$3,$4)',[extensionSecret,env,'priority',{id:issue,priority:'high'}]);
    assert.equal((await db.query('select body,priority from public.issues where id=$1',[issue])).rows[0].body,'Edited by another developer');
    const save = (environment, regenerate=false) => db.query('select public.save_project_review_link($1,$2,$3) as token',[project,environment,regenerate]);
    const token = (await save(env)).rows[0].token;
    assert.equal((await save(env2)).rows[0].token,token);
    assert.equal((await db.query('select * from public.preview_guest_review($1)',[token])).rows[0].environment_id,env2);
    const secret='a'.repeat(64);
    await db.query('select public.start_guest_session($1,$2,$3)',[token,'Guest',secret]);
    assert.equal((await db.query('select * from public.get_guest_session($1)',[secret])).rows.length,1);
    const handoff='e'.repeat(64), guestExtension='f'.repeat(64);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[secret,handoff]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[handoff,guestExtension]);
    await db.exec('reset role');
    const foreignEnv='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa';
    await db.query('insert into public.environments(id,project_id,name,origin) values($1,$2,$3,$4)',[foreignEnv,other,'Other','https://other.example']);
    await as(null,'anon');
    await assert.rejects(db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,foreignEnv,'list',{}]),/Not authorized/);
    await assert.rejects(db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,env,'delete',{id:issue}]),/Not authorized/);
    for (const [operation, field, value] of [['status','status','in_progress'],['priority','priority','low']]) {
      await db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,env,operation,{id:issue,[field]:value}]);
      await assert.rejects(db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,env,operation,{id:issue,[field]:'invalid'}]),/Invalid/);
      await assert.rejects(db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,foreignEnv,operation,{id:issue,[field]:value}]),/Not authorized/);
    }
    const guestReports = (await db.query('select public.report_operation($1,$2,$3,$4) as reports',[guestExtension,env,'list',{}])).rows[0].reports;
    assert.equal(guestReports[0].canChangeStatus,true);
    assert.equal(guestReports[0].canEdit,false);
    assert.equal(guestReports[0].status,'in_progress');
    assert.equal(guestReports[0].priority,'low');
    await assert.rejects(db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,env,'edit',{id:issue,body:'Forbidden'}]),/Not authorized/);
    await as(outsider);
    const next = (await save(env,true)).rows[0].token;
    assert.notEqual(token,next);
    await assert.rejects(db.query('select public.report_operation($1,$2,$3,$4)',[guestExtension,env,'status',{id:issue,status:'resolved'}]),/revoked/);
    assert.equal((await db.query('select * from public.preview_guest_review($1)',[token])).rows.length,0);
    assert.equal((await db.query('select * from public.get_guest_session($1)',[secret])).rows.length,0);
    assert.equal((await db.query('select * from public.project_review_links')).rows.length,1);
    await assert.rejects(db.query('select public.create_member_invite($1,$2,$3)',[project,'x@example.com','b'.repeat(64)]),/permission denied/);
    await as(null,'anon');
    await assert.rejects(save(env),/permission denied/);
    await assert.rejects(db.query('select * from public.project_review_links'),/permission denied/);
    await assert.rejects(db.query('select * from public.projects'),/permission denied/);
    await db.exec('reset role');
    await db.exec(await readFile(new URL('../migrations/202610050013_environment_review_links.sql', import.meta.url), 'utf8'));
    await as(outsider);
    const links = (await db.query('select * from public.environment_review_links')).rows;
    assert.equal(links.length,3);
    assert.equal(links.find(link => link.environment_id === env).token,next);
    const stagingToken=links.find(link => link.environment_id === env2).token;
    assert.notEqual(stagingToken,next);
    assert.equal((await db.query('select * from public.preview_guest_review($1)',[stagingToken])).rows[0].environment_id,env2);
    const automaticEnv='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb';
    await db.query('insert into public.environments(id,project_id,name,origin) values($1,$2,$3,$4)',[automaticEnv,project,'Automatic','https://automatic.example']);
    const automaticLink=(await db.query('select token from public.environment_review_links where environment_id=$1',[automaticEnv])).rows[0].token;
    assert.equal((await db.query('select * from public.preview_guest_review($1)',[automaticLink])).rows[0].environment_id,automaticEnv);
    const regenerated=(await db.query('select public.regenerate_environment_review_link($1) as token',[env2])).rows[0].token;
    assert.notEqual(regenerated,stagingToken);
    assert.equal((await db.query('select * from public.preview_guest_review($1)',[stagingToken])).rows.length,0);
    assert.equal((await db.query('select * from public.preview_guest_review($1)',[next])).rows.length,1);
    await as(null,'anon');
    await assert.rejects(db.query('select * from public.environment_review_links'),/permission denied/);
    await assert.rejects(db.query('select public.regenerate_environment_review_link($1)',[env2]),/permission denied/);
    await as(outsider);
    await db.query('select public.platform_delete_resource($1,$2)',[automaticEnv,'environment']);
    assert.equal((await db.query('select * from public.environment_review_links where environment_id=$1',[automaticEnv])).rows.length,0);
    await db.query('select public.platform_delete_resource($1,$2)',[project,'project']);
    assert.equal((await db.query('select * from public.projects where id=$1',[project])).rows.length,0);
  } finally { await db.close(); }
});
