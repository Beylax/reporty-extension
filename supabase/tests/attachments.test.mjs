import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import assert from 'node:assert/strict';
import { test } from 'node:test';

const developer=randomUUID(),second=randomUUID(),anonymous=randomUUID();
test('reply attachments: incremental migration preserves data, private reads, ownership, limits, revocation and cleanup paths',async()=>{
  const db=new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
      create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,is_anonymous boolean default false);
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;
      create function auth.uid() returns uuid language sql stable as $$ select (auth.jwt()->>'sub')::uuid $$;
      grant usage on schema auth,public to anon,authenticated;
      grant execute on function auth.uid(),auth.jwt() to anon,authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,metadata jsonb);`);
    await db.exec(await readFile(new URL('../initialize.sql',import.meta.url),'utf8'));
    await db.query('insert into auth.users(id,email,is_anonymous) values($1,$2,false),($3,$4,false),($5,$6,true)',[developer,'dev@example.com',second,'second@example.com',anonymous,'anonymous@example.com']);
    const as=async(id,role='authenticated')=>{
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify(id?{sub:id,is_anonymous:id===anonymous}:{})]);
      await db.exec(`set role ${role}`);
    };
    const project=randomUUID(),foreign=randomUUID(),env=randomUUID(),foreignEnv=randomUUID(),issue=randomUUID(),otherIssue=randomUUID();
    await as(developer);
    await db.query('insert into public.projects(id,name,created_by) values($1,$2,$3),($4,$5,$3)',[project,'Project',developer,foreign,'Foreign']);
    await db.query('insert into public.environments(id,project_id,name,origin) values($1,$2,$3,$4),($5,$6,$7,$8)',[env,project,'Production','https://one.example',foreignEnv,foreign,'Foreign','https://foreign.example']);
    const report=async(secret,target,operation,payload)=> (await db.query('select public.report_operation($1,$2,$3,$4) as data',[secret,target,operation,payload])).rows[0].data;
    const attachment=async(secret,target,operation,payload)=> (await db.query('select public.attachment_operation($1,$2,$3,$4) as data',[secret,target,operation,payload])).rows[0].data;
    const context={url:'https://one.example/',origin:'https://one.example',pagePath:'/',anchor:{kind:'pin',documentX:10,documentY:20},viewport:{width:1200,height:800,devicePixelRatio:1},scroll:{x:0,y:0}};
    for(const id of [issue,otherIssue]) await report(null,env,'create',{id,body:'Existing issue',context});
    await report(null,env,'reply',{id:issue,body:'Historical reply'});
    await db.exec('reset role; drop table public.comment_attachments; drop function public.attachment_operation(text,uuid,text,jsonb);');
    await db.exec(await readFile(new URL('../reply_attachments.sql',import.meta.url),'utf8'));
    await as(developer);
    const historical=await report(null,env,'thread',{id:issue});
    assert.equal(historical.comments[0].body,'Historical reply');
    assert.deepEqual(historical.comments[0].attachments,[]);
    await db.exec('reset role');
    assert.equal((await db.query('select count(*) as n from auth.users')).rows[0].n,3);
    await as(developer);
    const id=randomUUID(),payload={id,issueId:issue,name:'mockup.png',mime:'image/png',size:2500000};
    const reserved=await attachment(null,env,'reserve',payload);
    await assert.rejects(attachment(null,env,'read',{id,issueId:issue}),/unavailable/);
    await assert.rejects(db.query('select * from public.comment_attachments'),/permission denied/);
    await assert.rejects(db.query('insert into public.comment_attachments(id) values($1)',[randomUUID()]),/permission denied/);
    await assert.rejects(attachment(null,env,'reserve',{...payload,id:randomUUID(),size:2500001}),/Invalid attachment/);
    await assert.rejects(attachment(null,env,'reserve',{...payload,id:randomUUID(),size:0}),/Invalid attachment/);
    const replyId=randomUUID();
    await assert.rejects(report(null,env,'reply',{id:issue,body:'With image',attachments:[id],replyId}),/unavailable/);
    assert.equal((await report(null,env,'thread',{id:issue})).comments.length,1);
    await as(second);
    await assert.rejects(attachment(null,env,'reserve',payload),/unavailable/);
    await assert.rejects(attachment(null,env,'remove',{id,issueId:issue}),/Not authorized/);
    await assert.rejects(report(null,env,'reply',{id:issue,body:'Stolen',attachments:[id]}),/unavailable/);
    await db.exec('reset role');
    await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['attachments',reserved.path,{size:2500000}]);
    await as(developer);
    await assert.rejects(report(null,env,'reply',{id:otherIssue,body:'Wrong issue',attachments:[id]}),/unavailable/);
    await assert.rejects(report(null,env,'reply',{id:issue,body:'Duplicate',attachments:[id,id]}),/Invalid attachments/);
    await assert.rejects(report(null,env,'reply',{id:issue,body:'Too many',attachments:Array.from({length:6},()=>randomUUID())}),/Invalid attachments/);
    await report(null,env,'reply',{id:issue,body:'With image',attachments:[id],replyId});
    await report(null,env,'reply',{id:issue,body:'With image',attachments:[id],replyId});
    const thread=await report(null,env,'thread',{id:issue});
    assert.equal(thread.comments.length,2);
    assert.deepEqual(thread.comments[1].attachments,[{id,name:'mockup.png',mime:'image/png',size:2500000}]);
    await assert.rejects(report(null,env,'reply',{id:issue,body:'Another reply',attachments:[id]}),/unavailable/);
    await assert.rejects(attachment(null,env,'remove',{id,issueId:issue}),/Not authorized/);
    await as(second);
    assert.equal((await attachment(null,env,'read',{id,issueId:issue})).path,reserved.path);
    const link=(await db.query('select token from public.environment_review_links where environment_id=$1',[env])).rows[0].token;
    const guest='a'.repeat(64),code='b'.repeat(64),secret='c'.repeat(64);
    await as(null,'anon');
    await assert.rejects(attachment(null,env,'read',{id,issueId:issue}),/Not authorized/);
    await db.query('select public.start_guest_session($1,$2,$3)',[link,'Reviewer',guest]);
    await db.query("select public.create_guest_handoff($1,encode(sha256(convert_to($2,'UTF8')),'hex'))",[guest,code]);
    await db.query('select public.redeem_extension_handoff($1,$2)',[code,secret]);
    assert.equal((await attachment(secret,env,'read',{id,issueId:issue})).path,reserved.path);
    await assert.rejects(attachment(secret,foreignEnv,'read',{id,issueId:issue}),/Not authorized/);
    const drafts=[];
    for(let index=0;index<5;index++) {
      const draft=await attachment(secret,env,'reserve',{id:randomUUID(),issueId:issue,name:'file.txt',mime:'application/octet-stream',size:3}); drafts.push(draft);
    }
    await assert.rejects(attachment(secret,env,'reserve',{id:randomUUID(),issueId:issue,name:'sixth.txt',mime:'application/octet-stream',size:3}),/Maximum 5/);
    await db.exec('reset role');
    for(const draft of drafts) await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['attachments',draft.path,{size:3}]);
    await as(null,'anon');
    await report(secret,env,'reply',{id:issue,body:'Guest files',attachments:drafts.map(item=>item.id)});
    await assert.rejects(report(secret,env,'delete',{id:issue}),/Not authorized/);
    await as(anonymous);
    await assert.rejects(attachment(null,env,'read',{id,issueId:issue}),/Not authorized/);
    await as(developer);
    await db.query('select public.regenerate_environment_review_link($1)',[env]);
    await as(null,'anon');
    await assert.rejects(attachment(secret,env,'read',{id,issueId:issue}),/revoked/);
    await as(developer);
    const deleted=await report(null,env,'delete',{id:issue});
    assert.equal(deleted.attachment_paths.length,6);
    assert.ok(deleted.attachment_paths.includes(reserved.path));
    await assert.rejects(attachment(null,env,'read',{id,issueId:issue}),/unavailable/);
    // Storage objects must survive SQL deletion so the backend can remove them via Storage API.
    await db.exec('reset role');
    assert.equal((await db.query('select count(*) as n from storage.objects')).rows[0].n,6);
    await as(developer);
    const temporaryId=randomUUID();
    const temporary=await attachment(null,env,'reserve',{id:temporaryId,issueId:otherIssue,name:'cleanup.txt',mime:'application/octet-stream',size:1});
    await db.exec('reset role');
    await db.query('insert into storage.objects(bucket_id,name,metadata) values($1,$2,$3)',['attachments',temporary.path,{size:1}]);
    await as(developer);
    assert.equal((await attachment(null,env,'remove',{id:temporaryId,issueId:otherIssue})).path,temporary.path);
    // A failed Storage removal remains tracked and cannot be attached to a response.
    await assert.rejects(report(null,env,'reply',{id:otherIssue,body:'Removing file',attachments:[temporaryId]}),/unavailable/);
    assert.equal((await attachment(null,env,'remove',{id:temporaryId,issueId:otherIssue})).path,temporary.path);
    await attachment(null,env,'discard',{id:temporaryId,issueId:otherIssue});
    assert.equal(await attachment(null,env,'remove',{id:temporaryId,issueId:otherIssue}),null);
    const widget=(await db.query('select * from public.environment_widgets where environment_id=$1',[env])).rows[0];
    await db.query('update public.environment_widgets set enabled=true where environment_id=$1',[env]);
    const widgetSecret='d'.repeat(64);
    await as(null,'anon');
    await db.query('select public.start_widget_session($1,$2,$3,$4)',[widget.public_key,'https://one.example','Widget reviewer',widgetSecret]);
    await attachment(widgetSecret,env,'reserve',{id:randomUUID(),issueId:otherIssue,name:'widget.txt',mime:'application/octet-stream',size:1});
    await as(developer);
    await db.query('update public.environment_widgets set enabled=false where environment_id=$1',[env]);
    await as(null,'anon');
    await assert.rejects(attachment(widgetSecret,env,'reserve',{id:randomUUID(),issueId:otherIssue,name:'disabled.txt',mime:'application/octet-stream',size:1}),/disabled/);
    await as(developer);
    const pendingId=randomUUID();
    const pending=await attachment(null,env,'reserve',{id:pendingId,issueId:otherIssue,name:'draft.txt',mime:'application/octet-stream',size:1});
    const paths=(await db.query('select public.platform_delete_resource($1,$2) as data',[project,'project'])).rows[0].data;
    assert.ok(paths.includes(pending.path));
    await db.exec('reset role');
    const bucket=(await db.query("select * from storage.buckets where id='attachments'")).rows[0];
    assert.equal(bucket.public,false); assert.equal(bucket.file_size_limit,2500000);
    assert.equal((await db.query('select count(*) as n from public.comment_attachments')).rows[0].n,0);
  } finally { await db.close(); }
});
